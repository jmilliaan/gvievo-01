"""Generate the IB-01 board (ib01.kicad_pcb): outline, placement, net classes, silkscreen. No routing.

Run with KiCad's own Python (it has pcbnew):
    D:\\kicad\\bin\\python.exe gen_board.py
Input: ib01.net, exported from the schematic with
    kicad-cli sch export netlist -o ib01.net ib01.kicad_sch
Footprints are linked to the schematic symbols (same path), so "Update PCB from Schematic"
in KiCad keeps working.

This script is the master for placement until the board is edited by hand in KiCad.
"""
import json
import math
import os
import re

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
FPDIR = 'D:/kicad/share/kicad/footprints'
NETLIST = os.path.join(HERE, 'ib01.net')
OUT = os.path.join(HERE, 'ib01.kicad_pcb')
PRO = os.path.join(HERE, 'ib01.kicad_pro')

W, H = 250.0, 150.0          # board outline (owner: max 150 x 250 mm)
OX, OY = 30.0, 30.0          # outline origin on the page
ZONE_E_RIGHT = 68.0          # 48 V zone is x 0..68; gap 68..76 is a copper keep-out
ZONE_A_LEFT = 76.0

mm = pcbnew.FromMM


def P(x, y):
    return pcbnew.VECTOR2I(mm(OX + x), mm(OY + y))


# --------------------------------------------------------------------------- netlist
TOK = re.compile(r'\s*(?:(\()|(\))|"((?:[^"\\]|\\.)*)"|([^\s()"]+))', re.S)


def parse(text):
    stack, cur = [], []
    for m in TOK.finditer(text):
        lp, rp, qs, at = m.groups()
        if lp:
            stack.append(cur)
            cur = []
        elif rp:
            done, cur = cur, stack.pop()
            cur.append(done)
        else:
            cur.append(qs if qs is not None else at)
    return cur[0]


def kids(node, head):
    return [e for e in node if isinstance(e, list) and e and e[0] == head]


def one(node, head):
    k = kids(node, head)
    return k[0][1] if k else None


tree = parse(open(NETLIST, encoding='utf-8').read())
comps = {}
for c in kids(kids(tree, 'components')[0], 'comp'):
    comps[one(c, 'ref')] = {'value': one(c, 'value'), 'footprint': one(c, 'footprint'),
                            'uuid': one(c, 'tstamps')}
pinnet = {}                  # (ref, pin) -> net name
netnames = []
for n in kids(kids(tree, 'nets')[0], 'net'):
    name = one(n, 'name')
    netnames.append(name)
    for nd in kids(n, 'node'):
        pinnet[(one(nd, 'ref'), one(nd, 'pin'))] = name

# --------------------------------------------------------------------------- board
board = pcbnew.BOARD()
nets = {}
for name in netnames:
    ni = pcbnew.NETINFO_ITEM(board, name)
    board.Add(ni)
    nets[name] = ni

tb = board.GetTitleBlock()
tb.SetTitle('IB-01 interconnect board')
tb.SetDate('2026-11-16')
tb.SetRevision('draft 2')
tb.SetCompany('PT INTI GANDA PERDANA')
tb.SetComment(0, 'AGV I-PRIME, replaces the terminal blocks (A, B, C, E)')
tb.SetComment(1, 'Source: 02-pcb/pcb-study-001.md; generated by gen_board.py')

rect = pcbnew.PCB_SHAPE(board)
rect.SetShape(pcbnew.SHAPE_T_RECT)
rect.SetStart(P(0, 0))
rect.SetEnd(P(W, H))
rect.SetLayer(pcbnew.Edge_Cuts)
rect.SetWidth(mm(0.1))
board.Add(rect)

fps = {}


def load(ref):
    c = comps[ref]
    lib, name = c['footprint'].split(':')
    libdir = os.path.join(HERE, 'ib01.pretty') if lib == 'ib01' else os.path.join(FPDIR, lib + '.pretty')
    fp = pcbnew.FootprintLoad(libdir, name)
    if fp is None:
        raise SystemExit('footprint not found: ' + c['footprint'])
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    fp.SetReference(ref)
    fp.SetValue(c['value'])
    fp.SetPath(pcbnew.KIID_PATH('/' + c['uuid']))
    fp.SetSheetname('/')
    fp.SetSheetfile('ib01.kicad_sch')
    board.Add(fp)
    for pad in fp.Pads():
        key = (ref, pad.GetNumber())
        if key in pinnet:
            pad.SetNet(nets[pinnet[key]])
    fps[ref] = fp
    return fp


def crtyd(fp):
    b = fp.GetCourtyard(pcbnew.F_CrtYd).BBox()
    return (pcbnew.ToMM(b.GetX()) - OX, pcbnew.ToMM(b.GetY()) - OY,
            pcbnew.ToMM(b.GetRight()) - OX, pcbnew.ToMM(b.GetBottom()) - OY)


def put(ref, x, y, angle=0.0):
    """Pad 1 (footprint origin) at board coordinates (x, y)."""
    fp = fps.get(ref) or load(ref)
    fp.SetOrientationDegrees(angle)
    fp.SetPosition(P(x, y))
    return fp


def silk(x, y, s, size=1.0, angle=0.0, just='center'):
    t = pcbnew.PCB_TEXT(board)
    t.SetText(s)
    t.SetLayer(pcbnew.F_SilkS)
    t.SetTextSize(pcbnew.VECTOR2I(mm(size), mm(size)))
    t.SetTextThickness(mm(max(0.15, size * 0.15)))
    t.SetTextAngleDegrees(angle)
    t.SetHorizJustify({'left': pcbnew.GR_TEXT_H_ALIGN_LEFT, 'right': pcbnew.GR_TEXT_H_ALIGN_RIGHT,
                       'center': pcbnew.GR_TEXT_H_ALIGN_CENTER}[just])
    t.SetPosition(P(x, y))
    board.Add(t)


def silk_line(x1, y1, x2, y2, layer=pcbnew.F_SilkS, width=0.2):
    s = pcbnew.PCB_SHAPE(board)
    s.SetShape(pcbnew.SHAPE_T_SEGMENT)
    s.SetStart(P(x1, y1))
    s.SetEnd(P(x2, y2))
    s.SetLayer(layer)
    s.SetWidth(mm(width))
    board.Add(s)


