def connector(ref, x_left, y):
    """Place a connector so its courtyard starts at x_left and its pad row sits at y.
    Returns the courtyard right edge."""
    fp = put(ref, 0, y)
    x0, _, x1, _ = crtyd(fp)
    fp.SetPosition(P(x_left - x0, y))
    fp.Reference().SetVisible(False)
    x0, y0, x1, y1 = crtyd(fp)
    silk((x0 + x1) / 2, y0 - 1.2, '%s %s' % (ref, NAME[ref]), 1.0)
    for pad in fp.Pads():
        net = pad.GetNetname().lstrip('/')
        if net.startswith('unconnected'):
            net = 'NC'
        px = pcbnew.ToMM(pad.GetPosition().x) - OX
        silk(px, y1 + 0.6, net, 0.8, 90, 'right')
    return x1


def row(y, x_left, refs, gap=4.0):
    x = x_left
    for ref in refs:
        x = connector(ref, x, y) + gap
    return x


def fuse(n, x, y, label):
    """Fuse holder vertical, resistor and LED below it. x = holder centre, y = top of its courtyard."""
    fp = put('F%d' % n, 0, 0, 90)
    x0, y0, x1, y1 = crtyd(fp)
    fp.SetPosition(P(x - (x0 + x1) / 2, y - y0))
    fp.Reference().SetVisible(False)
    x0, y0, x1, y1 = crtyd(fp)
    cx = (x0 + x1) / 2
    silk(cx, y0 - 1.0, 'F%d' % n, 1.0)
    rr = put('R%d' % n, cx, y1 + 2.0, 0)
    rr.Reference().SetVisible(False)
    dd = put('D%d' % n, cx, y1 + 5.0, 0)
    dd.Reference().SetVisible(False)
    silk(cx, y1 + 8.6, label, 0.8)


# --------------------------------------------------------------------------- zone E: 48 V
for ref, x, y in (('J1', 4, 20), ('J4', 36, 20), ('J2', 4, 41), ('J5', 36, 41), ('J3', 4, 62),
                  ('J8', 36, 62), ('J6', 4, 83), ('J7', 36, 83)):
    connector(ref, x, y)
fuse(12, 15, 104, '5A -TA3')
fuse(13, 34, 104, '5A -TA4')
fuse(19, 53, 104, '5A SPARE')
silk(34, 4.0, '48 V ZONE (floating 1N48)', 1.2)

# --------------------------------------------------------------------------- zone A / B / C
row(17, ZONE_A_LEFT + 2, ['J10'])
row(17, 132, ['J11', 'J27', 'J28', 'J34', 'J35'])      # 12 V group, above the 12 V fuses
for i, (n, lab) in enumerate([(1, '2A SCAN'), (2, '3A SAFE'), (3, '2A IO'), (4, '2A HORN'), (5, '2A DISP'),
                              (6, '2A LINE'), (7, '2A FANS'), (8, '2A DRVL'), (9, '2A DRVR'),
                              (14, '2A SP1'), (15, '2A SP2'), (16, '2A SP3'),
                              (10, '7.5A IPC'), (11, '3A RFID'), (17, '3A SP1'), (18, '3A SP2')]):
    fuse(n, ZONE_A_LEFT + 6 + 10.0 * i, 31, lab)
row(70, ZONE_A_LEFT + 2, ['J12', 'J13', 'J14', 'J17', 'J18', 'J20'])
xe = row(89, ZONE_A_LEFT + 2, ['J29', 'J15', 'J16', 'J30'])
put('JP1', xe + 2, 87.73, 0).Reference().SetVisible(False)
silk(xe + 2, 84.0, 'JP1 TERM', 0.8)
put('R30', xe + 8.0, 90.27, 0)                      # flat, next to JP1 pin 2
row(108, ZONE_A_LEFT + 2, ['J21', 'J22', 'J23', 'J19'])
row(127, ZONE_A_LEFT + 2, ['J24', 'J25', 'J31', 'J32', 'J33'])
silk(ZONE_A_LEFT + 2, 4.0, '24 V / 12 V ZONE', 1.2, just='left')
silk(34, 134, 'IB-01 INTERCONNECT BOARD', 1.5)
silk(34, 137.5, 'AGV I-PRIME  PT INTI GANDA PERDANA', 1.0)
silk(34, 140, 'draft 2  2026-11-16', 1.0)

# --------------------------------------------------------------------------- holes (chassis)
for i, (x, y) in enumerate([(5, 5), (125, 5), (245, 5), (5, 145), (125, 145), (245, 145)]):
    put('H%d' % (i + 1), x, y).Reference().SetVisible(False)

# --------------------------------------------------------------------------- 48 V separation
silk_line((ZONE_E_RIGHT + ZONE_A_LEFT) / 2, 8, (ZONE_E_RIGHT + ZONE_A_LEFT) / 2, 142, width=0.3)
ka = pcbnew.ZONE(board)
ka.SetIsRuleArea(True)
ka.SetDoNotAllowTracks(True)
ka.SetDoNotAllowVias(True)
ka.SetDoNotAllowPads(True)
ka.SetDoNotAllowZoneFills(True)
ka.SetDoNotAllowFootprints(False)
ka.SetLayerSet(pcbnew.LSET.AllCuMask())
ka.SetZoneName('48V separation')
ol = ka.Outline()
ol.NewOutline()
for x, y in ((ZONE_E_RIGHT, 0), (ZONE_A_LEFT, 0), (ZONE_A_LEFT, H), (ZONE_E_RIGHT, H)):
    ol.Append(mm(OX + x), mm(OY + y))
board.Add(ka)

# Unplated holes H1 / H4 (48 V zone): no copper under the standoff, its washer or the screw head.
# Without this the 1N48 pour runs to 0.25 mm from the hole and the metal standoff sits on it
# with only solder mask in between (floating 48 V against chassis).
HOLE_KEEPOUT_R = 6.5         # mm; M4 washer is 4.5 mm radius
for ref in ('H1', 'H4'):
    c = fps[ref].GetPosition()
    hk = pcbnew.ZONE(board)
    hk.SetIsRuleArea(True)
    hk.SetDoNotAllowTracks(True)
    hk.SetDoNotAllowVias(True)
    hk.SetDoNotAllowPads(False)          # the hole itself is a pad
    hk.SetDoNotAllowZoneFills(True)
    hk.SetDoNotAllowFootprints(False)
    hk.SetLayerSet(pcbnew.LSET.AllCuMask())
    hk.SetZoneName('%s standoff, no copper' % ref)
    ol = hk.Outline()
    ol.NewOutline()
    for k in range(48):
        ang = 2 * math.pi * k / 48
        ol.Append(c.x + mm(HOLE_KEEPOUT_R * math.cos(ang)), c.y + mm(HOLE_KEEPOUT_R * math.sin(ang)))
    board.Add(hk)

# --------------------------------------------------------------------------- 48 V trunk, J3 to the fuse inputs
# 1P48 from J3 pin 1 to F12 / F13 / F19 sits in front of 15 A of fuses with only the 32 A main breaker
# ahead of it, so it is laid here as a 5 mm top track (about 20 K rise at 15 A, estimate) and not left to
# the autorouter's 1.5 mm class width. Path: west of J3, down the left edge clear of J6, along the fuse inputs.
TRUNK_W = 5.0
TRUNK_X = 6.5                # board x of the vertical leg (track edge 4 mm from the board edge)


def pad_at(ref, num):
    return [p.GetPosition() for p in fps[ref].Pads() if p.GetNumber() == num]


j3 = pad_at('J3', '1')[0]
fuse_in = [q for ref in ('F12', 'F13', 'F19') for q in pad_at(ref, '1')]
if len(set(q.y for q in fuse_in)) != 1:
    raise SystemExit('48 V fuse inputs are not on one line: the trunk path needs redrawing')
ybus = fuse_in[0].y
xl = mm(OX + TRUNK_X)
xs = sorted(q.x for q in fuse_in)


def trunk(pts, width, net='/1P48'):
    for p0, p1 in zip(pts, pts[1:]):
        tr = pcbnew.PCB_TRACK(board)
        tr.SetStart(p0)
        tr.SetEnd(p1)
        tr.SetWidth(mm(width))
        tr.SetLayer(pcbnew.F_Cu)
        tr.SetNet(nets[net])
        board.Add(tr)


# Leg from J3 down the left edge, then a pad-wide track with a corner on every fuse input pad (the
# autorouter only counts a pad as connected where a track ends on it).
trunk([j3, pcbnew.VECTOR2I(xl, j3.y), pcbnew.VECTOR2I(xl, ybus)] + [pcbnew.VECTOR2I(x, ybus) for x in xs], 2.8)
trunk([j3, pcbnew.VECTOR2I(xl, j3.y), pcbnew.VECTOR2I(xl, ybus)], TRUNK_W)
# The 5 mm of copper along the fuses lies on the upper side of the pads, so the LED resistors below keep
# room for their vias. Together with the pad-wide track the copper is 5.3 mm wide.
yb = ybus - mm(1.4)
trunk([pcbnew.VECTOR2I(xl, yb), pcbnew.VECTOR2I(xs[-1], yb)], TRUNK_W)

# 24 V feed, J10 pin 1 to the first fuse input: the only way into the 24 V bus (up to 4.2 A). Laid here at
# the full 2.0 mm, down the gap between F1 and F2; the autorouter necked it to 1.0 mm.
j10 = pad_at('J10', '1')[0]
f1 = max(pad_at('F1', '1'), key=lambda q: q.x)          # F1 input pad on the F2 side
xg = (f1.x + min(q.x for q in pad_at('F2', '1'))) // 2  # middle of the gap between the two holders
trunk([j10, pcbnew.VECTOR2I(xg, j10.y + abs(xg - j10.x)), pcbnew.VECTOR2I(xg, f1.y), f1], 2.0, '/1P24')

# --------------------------------------------------------------------------- copper pours
def zone(net, layer, pts, priority=0, solid=False, clearance=0.5):
    z = pcbnew.ZONE(board)
    z.SetLayer(layer)
    z.SetNet(nets[net])
    z.SetAssignedPriority(priority)
    z.SetPadConnection(pcbnew.ZONE_CONNECTION_FULL if solid else pcbnew.ZONE_CONNECTION_THERMAL)
    z.SetMinThickness(mm(0.3))
    z.SetLocalClearance(mm(clearance))
    z.SetThermalReliefGap(mm(0.5))
    z.SetThermalReliefSpokeWidth(mm(1.0))
    z.SetZoneName(net.lstrip('/') + (' top' if layer == pcbnew.F_Cu else ' bottom'))
    ol = z.Outline()
    ol.NewOutline()
    for x, y in pts:
        ol.Append(mm(OX + x), mm(OY + y))
    board.Add(z)


def box(x1, y1, x2, y2):
    return [(x1, y1), (x2, y1), (x2, y2), (x1, y2)]


zone('/1N48', pcbnew.B_Cu, box(1, 1, ZONE_E_RIGHT - 1, H - 1), solid=True, clearance=0.8)        # 48 V return, whole zone E
zone('/2P48', pcbnew.F_Cu, box(4, 13, 63, 27), priority=1, solid=True, clearance=0.8)            # J1 -> J4, 13 A
zone('/3P48', pcbnew.F_Cu, box(4, 34, 63, 48), priority=1, solid=True, clearance=0.8)            # J2 -> J5, 13 A
# 24 V return: zone A without the 12 V corner (no overlap, so the autorouter sees two clean planes)
zone('/1N24', pcbnew.B_Cu, [(ZONE_A_LEFT + 1, 1), (129, 1), (129, 28), (196, 28), (196, 59), (W - 1, 59),
                            (W - 1, H - 1), (ZONE_A_LEFT + 1, H - 1)])
zone('/1N12', pcbnew.B_Cu, [(130, 1), (W - 1, 1), (W - 1, 58), (197, 58), (197, 27), (130, 27)])   # 12 V corner

# 48 V LED cathodes are SMD on top: a via each down to the 1N48 plane. (The 24 V / 12 V LEDs are
# routed by the autorouter, because 1N24 / 1N12 are routed as tracks too, see route.py.)
for ref, fp in fps.items():
    if ref not in ('D12', 'D13', 'D19'):
        continue
    for pad in fp.Pads():
        if pad.GetNumber() != '1':
            continue
        pos = pad.GetPosition()
        vpos = pcbnew.VECTOR2I(pos.x - mm(2.0), pos.y)
        v = pcbnew.PCB_VIA(board)
        v.SetPosition(vpos)
        v.SetWidth(mm(0.8))
        v.SetDrill(mm(0.4))
        v.SetNet(pad.GetNet())
        board.Add(v)
        tr = pcbnew.PCB_TRACK(board)
        tr.SetStart(pos)
        tr.SetEnd(vpos)
        tr.SetWidth(mm(0.4))
        tr.SetLayer(pcbnew.F_Cu)
        tr.SetNet(pad.GetNet())
        board.Add(tr)

# --------------------------------------------------------------------------- fab notes
t = pcbnew.PCB_TEXT(board)
t.SetText('FAB: FR4 1.6 mm, 2 layers, 2 oz (70 um) copper both sides, HASL lead-free, green mask, white silk.\n'
          'Board 250 x 150 mm. 6 x M4 holes to chassis. Generated by gen_board.py, draft 2, 2026-11-16.')
t.SetLayer(pcbnew.Cmts_User)
t.SetTextSize(pcbnew.VECTOR2I(mm(1.5), mm(1.5)))
t.SetHorizJustify(pcbnew.GR_TEXT_H_ALIGN_LEFT)
t.SetPosition(P(0, H + 10))
board.Add(t)

filler = pcbnew.ZONE_FILLER(board)
filler.Fill(board.Zones())

missing = sorted(set(comps) - set(fps))
